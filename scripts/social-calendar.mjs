// Builds ready-to-paste social copy for every post in the daily blog calendar.
// Run: node scripts/social-calendar.mjs
// Writes docs/social-calendar-2026.md (human) and docs/social-calendar-2026.csv
// (for scheduling tools). Wording follows the site rules: no payment-timing
// promises, no review/rating claims, no response-time promises.
import fs from "node:fs"
import { BLOG_SCHEDULE, displayDate } from "../lib/blog-schedule.ts"

const SITE = "https://houstonsuperiorpainting.com"
const PHONE = "(346) 594-5960"
const BANNED = /no upfront|nothing due|pay nothing|\$0 due|4\.9|200\+ reviews|within 24 hours|same[- ]day/i

const rows = BLOG_SCHEDULE.map((p) => {
  const url = `${SITE}/blog/${p.slug}`
  const gbp = `${p.title}\n\n${p.excerpt}\n\nRead the guide, then request a free written estimate: ${PHONE}.`
  const social = `${p.excerpt}\n\nFull guide: ${url}\n\nFree written estimates · ${PHONE} · Houston Superior Painting`
  for (const t of [gbp, social]) if (BANNED.test(t)) throw new Error(`banned wording in ${p.slug}`)
  return { date: p.publishOn, title: p.title, url, gbp, social, keyword: p.keyword }
})

const md = [
  "# Social calendar: one post a day with the blog (generated)",
  "",
  "Generated by `node scripts/social-calendar.mjs` from `lib/blog-schedule.ts`. Post each item on its date,",
  "**after 6:00 AM Houston time** (the blog post goes live then; earlier, the link returns 404).",
  "",
  "- **Google Business Profile:** post the GBP text as an Update; button **Learn more** → the URL.",
  "- **Facebook / Instagram:** use the social caption; on Instagram put the URL in the bio or a link sticker.",
  "",
  ...rows.flatMap((r) => [
    `## ${displayDate(r.date)}: ${r.title}`,
    "",
    `URL: ${r.url}`,
    "",
    "**Google Business Profile** (button: Learn more → URL)",
    "",
    "```",
    r.gbp,
    "```",
    "",
    "**Facebook / Instagram**",
    "",
    "```",
    r.social,
    "```",
    "",
  ]),
].join("\n")

const csvEsc = (s) => `"${String(s).replace(/"/g, '""')}"`
const csv = [
  ["date", "post_after_houston_time", "platform", "text", "link", "keyword"].join(","),
  ...rows.flatMap((r) => [
    [r.date, "06:00", "Google Business Profile", r.gbp, r.url, r.keyword].map(csvEsc).join(","),
    [r.date, "06:00", "Facebook/Instagram", r.social, r.url, r.keyword].map(csvEsc).join(","),
  ]),
].join("\n")

